#!/usr/bin/env python3
"""Compile pinned upstream sources privately, one compiler process at a time."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[1]
PIN = '7411374cef282756ef5a8984ce896fb8db797e9e'

def win(path):
    return 'Z:' + str(Path(path).resolve()).replace('/', '\\')

def environment():
    vc = ROOT / '.tools/msvc700/Vc7'
    sdk = ROOT / '.tools/dx8sdk'
    lock=tomllib.loads((ROOT/'config/tools.lock.toml').read_text())
    for path,expected in [(vc/'bin/cl.exe',lock['msvc70']['compiler_sha256']),(vc/'bin/c1xx.dll',lock['msvc70']['frontend_sha256']),(vc/'bin/link.exe',lock['msvc70']['linker_sha256'])]:
        if hashlib.sha256(path.read_bytes()).hexdigest()!=expected:raise ValueError('pinned VC7.0 tool changed: '+str(path))
    for name,expected in lock['dx8sdk']['files'].items():
        if hashlib.sha256((sdk/name).read_bytes()).hexdigest()!=expected:raise ValueError('pinned DirectX SDK changed: '+name)
    env = os.environ.copy()
    env.update(WINEDEBUG='-all', WINEPREFIX=str(ROOT / '.tools/wine'), DISPLAY='', WAYLAND_DISPLAY='', WINEDLLOVERRIDES='winemenubuilder.exe=d')
    env['INCLUDE'] = ';'.join(win(p) for p in [sdk/'include', vc/'include', vc/'PlatformSDK/include'])
    env['LIB'] = ';'.join(win(p) for p in [sdk/'lib', vc/'lib', vc/'PlatformSDK/lib'])
    return env

def run(args, cwd, log, env):
    cmd = ['taskset','-c',str(min(os.sched_getaffinity(0))),'nice','-n','15','wine', *map(str,args)]
    result = subprocess.run(cmd, cwd=cwd, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    log.write_bytes(result.stdout)
    if result.returncode:
        sys.stderr.write(result.stdout.decode(errors='replace'))
        raise RuntimeError(f'compiler failed; see {log}')
    return result.stdout.decode(errors='replace')

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--stock', action='store_true')
    parser.add_argument('--source-root', type=Path)
    parser.add_argument('--only')
    args = parser.parse_args()
    ref = ROOT/'_reference/gensokyoclub-th06'
    if subprocess.check_output(['git','-C',str(ref),'rev-parse','HEAD'],text=True).strip()!=PIN:
        raise ValueError('upstream revision differs from pinned baseline')
    source = args.source_root.resolve() if args.source_root else ref
    tag = 'stock' if args.stock else 'upstream'
    if args.source_root: tag = 'authored'
    out = ROOT/'build'/tag
    out.mkdir(parents=True,exist_ok=True)
    env = environment()
    vc = ROOT/'.tools/msvc700/Vc7'
    compiler = vc/'bin/cl.exe'
    if not args.stock:
        lock=tomllib.loads((ROOT/'config/tools.lock.toml').read_text())
        pragma_sha=hashlib.sha256((ref/'scripts/pragma_var_order.cpp').read_bytes()).hexdigest()
        if pragma_sha!=lock['msvc70']['pragma_source_sha256']:raise ValueError('upstream compiler wrapper source changed')
        patched = ROOT/'.tools/vc70-patched/bin'
        if not (patched/'C1XXOrig.dll').exists():
            shutil.copytree(vc/'bin',patched,dirs_exist_ok=True)
            output=out/'pragma_var_order.dll'
            run([compiler,'/nologo','/LD',win(ref/'scripts/pragma_var_order.cpp'),'/Fo'+win(out/'pragma.obj'),'/Fe'+win(output),'/link','/implib:'+win(out/'pragma.lib')],out,out/'pragma.log',env)
            (patched/'c1xx.dll').rename(patched/'C1XXOrig.dll')
            shutil.copyfile(output,patched/'c1xx.dll')
            (patched/'frontend-receipt.json').write_text(json.dumps({'pragma_source_sha256':pragma_sha,'wrapper_sha256':hashlib.sha256((patched/'c1xx.dll').read_bytes()).hexdigest(),'original_sha256':hashlib.sha256((patched/'C1XXOrig.dll').read_bytes()).hexdigest()},indent=2)+'\n')
        wrapper=json.loads((patched/'frontend-receipt.json').read_text())
        if wrapper['pragma_source_sha256']!=pragma_sha or wrapper['wrapper_sha256']!=hashlib.sha256((patched/'c1xx.dll').read_bytes()).hexdigest() or wrapper['original_sha256']!=lock['msvc70']['frontend_sha256']:raise ValueError('compiler wrapper receipt mismatch')
        compiler = patched/'cl.exe'
    generated=out/'autogenerated';generated.mkdir(exist_ok=True)
    subprocess.run([sys.executable,str(ref/'scripts/generate_i18n.py'),str(source/'src/i18n.tpl'),str(generated/'i18n.hpp')],check=True)
    sys.path.insert(0,str(ref/'scripts'))
    import configure
    old=Path.cwd()
    os.chdir(ref)
    try: configure.configure(configure.BuildType.NORMAL,configure.BuildVersion.VER_102h,'')
    finally: os.chdir(old)
    # Read the upstream-generated commands, preserving per-owner flags and PCH mode.
    lines=(ref/'build.ninja').read_text().replace('$\n    ', '').splitlines()
    common=next(s.split(' = ',1)[1] for s in lines if s.startswith('cl_common_flags = '))
    flags=next(s.split(' = ',1)[1] for s in lines if s.startswith('cl_flags = '))
    pbg=next(s.split(' = ',1)[1] for s in lines if s.startswith('cl_flags_pbg3 = '))
    tree_receipt=[{'path':str(p.relative_to(source)), 'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for p in sorted((source/'src').rglob('*')) if p.is_file()]
    commands=[]
    for i,line in enumerate(lines):
        if not line.startswith('build $builddir/') or ': cc' not in line: continue
        output,rest=line[6:].split(': ',1);kind,src=rest.split(' ',1);src=src.split(' |')[0].strip()
        if not src.startswith('src/'): continue
        name=Path(output).stem
        if args.only and name!=args.only:continue
        local=flags
        if i+1<len(lines) and lines[i+1].startswith('  cl_flags = '):local=lines[i+1].split(' = ',1)[1]
        local=local.replace('$cl_flags_pbg3',pbg).replace('$cl_flags',flags).replace('$cl_common_flags',common)
        local=local.replace('$builddir/autogenerated',win(generated)).replace('/I src','/I '+win(source/'src')).replace('/I 3rdparty/munit','')
        obj=out/(name+'.obj'); cmd=[compiler,'/nologo',*local.split(),'/Fp'+win(out/(name+'.pch')),'/c',win(source/src),'/Fd'+win(out/(name+'.pdb')),'/Fo'+win(obj)]
        if kind=='cc_pch':cmd.insert(2,'/Ycstdafx.h')
        print(f'{tag}: {name}',flush=True)
        run(cmd,source,out/(name+'.log'),env)
        commands.append({'source':src,'source_sha256':hashlib.sha256((source/src).read_bytes()).hexdigest(),'object':str(obj.relative_to(ROOT)),'command':list(map(str,cmd)),'object_sha256':hashlib.sha256(obj.read_bytes()).hexdigest()})
        # Matching needs COFF objects and receipts, never these bulky PCH/PDB files.
        for p in out.iterdir():
            if p.suffix.lower() in {'.pch', '.pdb'}: p.unlink()
    (out/'build-receipt.json').write_text(json.dumps({'upstream_commit':PIN,'compiler_sha256':hashlib.sha256(compiler.read_bytes()).hexdigest(),'frontend_sha256':hashlib.sha256((compiler.parent/'c1xx.dll').read_bytes()).hexdigest(),'source_tree':tree_receipt,'commands':commands},indent=2)+'\n')

if __name__=='__main__':main()
